function buildSections(seed: ArticleSeed): LearnSection[] {
  return [
    {
      type: 'heading',
      body: '核心思路',
    },
    {
      type: 'text',
      body: seed.focus,
    },
    {
      type: 'comparison',
      title: '错误 vs 正确',
      body: '把易错表达换成更稳妥的考试表达。',
      wrongExample: seed.wrongExample,
      rightExample: seed.rightExample,
      note: seed.action,
    },
    {
      type: 'tip',
      title: '一句话速记',
      body: seed.quickCard,
    },
  ]
}

function buildRelatedIds(id: string, category: LearnCategory): string[] {
  const sameCategoryIds = articleSeeds
    .filter((item) => item.category === category && item.id !== id)
    .map((item) => item.id)

  return sameCategoryIds.slice(0, 2)
}

export const learnArticles: LearnArticle[] = articleSeeds.map((seed) => ({
  ...seed,
  content: buildSections(seed),
  relatedArticleIds: buildRelatedIds(seed.id, seed.category),
}))

export function getArticleById(articleId: string): LearnArticle | undefined {
  return learnArticles.find((article) => article.id === articleId)
}

export function getArticlesByCategory(category: LearnCategory): LearnArticle[] {
  return learnArticles.filter((article) => article.category === category)
}

